const REVERSE = new Map(Object.entries(NAMED).map(([name, ch]) => [ch, name]));
const SPECIAL = /[&<>"']/;

export const html = defineTransform({
  kind: 'transform',
  id: 'html',
  category: 'encodings',
  keywords: ['html', 'entities', 'escape', 'xml', 'character reference', 'xss'],
  sample: { encode: '<a href="/?q=café&lang=fa">«سلام» © 2026 → ∞</a>' },
  options: [
    opt.select('format', ['named', 'decimal', 'hex'], 'named', { control: 'segmented' }),
    opt.select('scope', ['special', 'nonAscii', 'all'], 'nonAscii', { directions: ['encode'] }),
  ],
  encode: (input, o) => {
    let out = '';
    for (const ch of input) {
      const cp = ch.codePointAt(0)!;
      const needs =
        o.scope === 'all'
          ? !/\s/.test(ch)
          : SPECIAL.test(ch) || (o.scope === 'nonAscii' && cp > 126);
      if (!needs) {
        out += ch;
        continue;
      }
      const name = o.format === 'named' ? REVERSE.get(ch) : undefined;
      if (name) out += `&${name};`;
      else if (o.format === 'decimal') out += `&#${cp};`;
      else out += `&#x${cp.toString(16).toUpperCase()};`;
    }
    return out;
  },
  decode: (input) =>
    input.replace(/&(#x[0-9a-f]+|#\d+|[a-z][a-z0-9]*);/gi, (match, body: string) => {
      if (body[0] === '#') {
        const cp =
          body[1] === 'x' || body[1] === 'X'
            ? parseInt(body.slice(2), 16)
            : parseInt(body.slice(1), 10);
        return cp > 0 && cp <= 0x10ffff ? String.fromCodePoint(cp) : match;
      }
      return NAMED[body] ?? match;
    }),
  detect: (input) => ((input.match(/&(#x?[0-9a-f]+|[a-z]+);/gi)?.length ?? 0) >= 2 ? 0.9 : 0),
});
