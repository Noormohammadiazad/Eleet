/**
 * Builds the archive imagery used by the historical dossiers.
 *
 * Input: a directory with one sub-directory per artifact, each holding a single
 * downloaded original (`<dir>/<id>/original.jpg|png`). The originals are
 * public-domain or CC0 scans from Wikimedia Commons; their provenance and
 * licence are recorded by hand in `src/lib/content/archive.ts`.
 *
 * Output:
 *   public/archive/<id>-<width>.avif|webp   responsive renditions
 *   src/lib/content/archive-media.ts        intrinsic sizes, widths and a
 *                                           ~300-byte blurred placeholder
 *
 * Images are lazy-loaded, excluded from the service-worker precache, and
 * carry explicit width/height so they never shift the layout while loading.
 *
 * Usage (sharp is not a project dependency, so CI never needs it):
 *
 *   npm install --no-save sharp
 *   node tooling/build-archive.ts <dir>
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

interface SharpImage {
  metadata(): Promise<{ width?: number; height?: number }>;
  rotate(): SharpImage;
  resize(width: number, height?: number, options?: Record<string, unknown>): SharpImage;
  avif(options: Record<string, unknown>): SharpImage;
  webp(options: Record<string, unknown>): SharpImage;
  toFile(path: string): Promise<unknown>;
  toBuffer(): Promise<Uint8Array>;
}
type Sharp = (input: string) => SharpImage;

const STEPS = [480, 960, 1440];
const OUT_DIR = 'public/archive';
const MODULE = 'src/lib/content/archive-media.ts';

/** Widths to render: the standard steps below the original, then the original (capped). */
export function renditionWidths(original: number): number[] {
  const widths = STEPS.filter((w) => w < original * 0.95);
  const top = Math.min(original, STEPS.at(-1)!);
  if (!widths.includes(top)) widths.push(top);
  return widths;
}

async function main(): Promise<void> {
  const dir = process.argv[2];
  if (!dir) throw new Error('usage: node tooling/build-archive.ts <dir>');
  const moduleName = 'sharp';
  const sharp = ((await import(moduleName)) as { default: Sharp }).default;
  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(dirname(MODULE), { recursive: true });

  const entries: string[] = [];
  for (const id of readdirSync(dir).sort()) {
    const file = readdirSync(join(dir, id)).find((f) => /^original\.(jpe?g|png|webp)$/i.test(f));
    if (!file) continue;
    const source = join(dir, id, file);
    const { width = 0, height = 0 } = await sharp(source).metadata();
    const widths = renditionWidths(width);
    for (const w of widths) {
      const base = join(OUT_DIR, `${id}-${w}`);
      await sharp(source)
        .rotate()
        .resize(w)
        .avif({ quality: 52, effort: 6 })
        .toFile(`${base}.avif`);
      await sharp(source)
        .rotate()
        .resize(w)
        .webp({ quality: 76, effort: 6 })
        .toFile(`${base}.webp`);
    }
    const tiny = await sharp(source).rotate().resize(24).webp({ quality: 42 }).toBuffer();
    const lqip = `data:image/webp;base64,${Buffer.from(tiny).toString('base64')}`;
    entries.push(
      `  '${id}': { width: ${width}, height: ${height}, widths: [${widths.join(', ')}], lqip: '${lqip}' },`,
    );
    console.log(`${id}: ${width}×${height} → ${widths.join(', ')}`);
  }

  writeFileSync(
    MODULE,
    `/* Generated by tooling/build-archive.ts — do not edit by hand. */
export interface ArchiveMedia {
  /** Intrinsic size of the largest rendition's source. */
  readonly width: number;
  readonly height: number;
  /** Rendered widths, available as public/archive/<id>-<width>.avif and .webp. */
  readonly widths: readonly number[];
  /** A tiny blurred WebP shown while the real image loads. */
  readonly lqip: string;
}

export const ARCHIVE_MEDIA = {
${entries.join('\n')}
} as const satisfies Record<string, ArchiveMedia>;

export type ArchiveId = keyof typeof ARCHIVE_MEDIA;
`,
  );
}

// Run only when executed directly (the tests import `renditionWidths`).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
